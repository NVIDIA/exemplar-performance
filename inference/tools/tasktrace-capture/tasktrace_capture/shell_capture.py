"""Portable Bash subcommand timing for instrumented TaskTrace Capture runs.

Trajectory data records an agent tool action such as ``cd /app && sed ...`` as
one action. When enabled before the agent starts, this module causes Bash tool
shells to emit begin/end events for individual simple commands, including
builtins such as ``cd``. Both Docker and Enroot write the same trial artifacts.
"""

